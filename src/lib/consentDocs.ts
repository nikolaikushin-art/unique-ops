export function docToText(d: ConsentDoc): string {
  const out: string[] = [d.title.toUpperCase(), `Редакция от ${DOCS_DATE_LABEL}`, `Основание: ${d.law}`, ''];
  for (const s of d.sections) {
    out.push(s.h);
    (s.p ?? []).forEach((t) => out.push(t));
    (s.ul ?? []).forEach((t) => out.push(`• ${t}`));
    out.push('');
  }
  return out.join('\n');
}
